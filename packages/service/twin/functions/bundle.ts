import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { build, type Plugin } from 'esbuild';

export type BundleVersion = '0.4.0' | '0.6.3' | '0.7.0';

const SHARED_FUNCTIONS = ['closeAccount', 'probeVersionCheck', 'setRelationship'] as const;

const FUNCTIONS: Record<BundleVersion, readonly string[]> = {
  '0.4.0': ['closeAccount'],
  '0.6.3': SHARED_FUNCTIONS,
  '0.7.0': SHARED_FUNCTIONS,
};

const ROOT = fileURLToPath(new URL('../../../../', import.meta.url));
const SRC = fileURLToPath(new URL('./src/', import.meta.url));

const dropFs: Plugin = {
  name: 'drop-fs',
  setup(b) {
    b.onResolve({ filter: /^fs$/ }, () => ({ path: 'fs', external: true, sideEffects: false }));
  },
};

export async function buildBundle(version: BundleVersion): Promise<string> {
  const names = FUNCTIONS[version];

  const entry = [
    `export { createClient } from '@osdk/client';`,
    ...names.map((name) => `import ${name} from './${name}.ts';`),
    `export const functions = { ${names.join(', ')} };`,
  ].join('\n');

  const result = await build({
    stdin: { contents: entry, resolveDir: SRC, sourcefile: 'functions.ts', loader: 'ts' },
    absWorkingDir: ROOT,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2024',
    legalComments: 'eof',
    banner: {
      js: `/* oxlint-disable */\n// Generated by bundle.ts from src/. Do not edit.\n// Third-party license notices for bundled dependencies: see NOTICE and THIRD_PARTY_NOTICES.md.`,
    },
    plugins: [dropFs],
    metafile: true,
    write: false,
    logLevel: 'silent',
  });

  const imports = Object.values(result.metafile.outputs).flatMap((output) => output.imports.map((i) => i.path));

  if (imports.length > 0) throw new Error(`The bundle of ${version} imports ${imports.join(', ')}.`);

  const [output] = result.outputFiles;

  if (!output) throw new Error(`esbuild wrote no bundle for ${version}.`);

  return output.text.replaceAll(/^\s*\/\/ (?:es|ox)lint-disable.*\n/gm, '');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const version of Object.keys(FUNCTIONS) as BundleVersion[]) {
    if (version === '0.7.0') continue;

    writeFileSync(new URL(`./${version}.bundle.js`, import.meta.url), await buildBundle(version));
  }
}
